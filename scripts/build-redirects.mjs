/** Generate public/.htaccess from the two redirect CSVs.
 *
 * Two sources, because they answer to different people:
 *
 *   data/legacy-redirects.csv  written by a person, for the addresses the
 *                              WordPress site answered. The category, tag and
 *                              author archives.
 *   data/retired-urls.csv      written by the sync, when a slug changes in
 *                              Notion and an address moves with it.
 *
 * A row with an empty `to` becomes `410 Gone` rather than a 404: Gone means
 * "this was here and we removed it on purpose", which is what we want to tell a
 * crawler about a retired page, and it stops the address being retried for
 * months.
 *
 * `.htaccess` is generated. Never edit it, edit this file or the CSVs. A test
 * fails if the committed file is not what this would write today.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'public/.htaccess';

function read(path) {
  let raw;
  try { raw = readFileSync(path, 'utf8'); } catch { return []; }
  return raw.trim().split('\n').slice(1)
    .map((l) => l.trim()).filter(Boolean)
    .map((line) => {
      const [from, to = '', ...why] = line.split(',');
      return { from: from.trim(), to: to.trim(), why: why.join(',').trim() };
    })
    .filter((r) => r.from);
}

// Later wins, so a slug the sync moved beats a stale hand-written line about
// the same address. The sync is the one that watched it happen.
const rules = new Map();
for (const r of [...read('data/legacy-redirects.csv'), ...read('data/retired-urls.csv')]) {
  rules.set(r.from, r);
}

/** A rule pointing at an address that is itself redirected is two hops, which
 *  is a slower page and a diluted ranking. Resolve the chain here rather than
 *  making the browser walk it. A cycle is a bug in the CSVs; break it rather
 *  than hanging, and say so. */
function resolve(from, seen = new Set()) {
  const rule = rules.get(from);
  if (!rule || !rule.to) return from;
  // A fragment is not part of what the server matches, so a rule pointing at
  // `/faq/#tag=x` chains through `/faq/` if that ever moves.
  const [target] = rule.to.split('#');
  if (seen.has(from)) {
    console.warn(`  ! redirect cycle at ${from}; leaving it as one hop`);
    return rule.to;
  }
  seen.add(from);
  if (!rules.has(target)) return rule.to;
  const resolved = resolve(target, seen);
  return rule.to.includes('#') ? resolved.split('#')[0] + '#' + rule.to.split('#')[1] : resolved;
}

const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const lines = [
  '# GENERATED by scripts/build-redirects.mjs, do not edit.',
  '# Sources: data/legacy-redirects.csv (people), data/retired-urls.csv (the sync).',
  '# Run `npm run redirects` after adding or renaming content.',
  '',
  'Options -Indexes',
  '',
  '<IfModule mod_rewrite.c>',
  '  RewriteEngine On',
  '',
];

const gone = [];
const moved = [];
for (const rule of [...rules.values()].sort((a, b) => a.from.localeCompare(b.from))) {
  if (!rule.to) gone.push(rule);
  else moved.push({ ...rule, to: resolve(rule.from) });
}

if (moved.length) {
  lines.push('  # Moved permanently.');
  for (const r of moved) {
    if (r.why) lines.push(`  # ${r.why}`);
    // `[NE]` keeps the fragment intact: without it Apache escapes the `#` and
    // the tag filter never sees the hash it needs.
    const flags = r.to.includes('#') ? 'R=301,NE,L' : 'R=301,L';
    lines.push(`  RewriteRule "^${escape(r.from.replace(/^\//, ''))}$" "${r.to}" [${flags}]`);
  }
  lines.push('');
}
if (gone.length) {
  lines.push('  # Retired on purpose. 410 rather than 404: it was here, and it is not coming back.');
  for (const r of gone) {
    if (r.why) lines.push(`  # ${r.why}`);
    lines.push(`  RewriteRule "^${escape(r.from.replace(/^\//, ''))}$" - [G,L]`);
  }
  lines.push('');
}

lines.push(
  '</IfModule>',
  '',
  '# The body of a 410, and of a 404. Both are real pages in the build, but',
  '# Astro special-cases 404 and emits it at the root as 404.html, while 410 is',
  '# an ordinary page and gets a directory. check:urls knows the difference.',
  'ErrorDocument 404 /404.html',
  'ErrorDocument 410 /410/index.html',
  '',
);

writeFileSync(OUT, lines.join('\n'));
console.log(`redirects: ${moved.length} moved, ${gone.length} gone → ${OUT}`);
